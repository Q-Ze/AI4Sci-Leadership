def _resolved(settings):
    values = {field["path"]: field["default"] for field in PLOT_SCHEMA}
    values.update(settings or {})
    return values


def prepare_data():
    return pd.DataFrame(_DATA)


def render(data, settings):
    cfg = _resolved(settings)
    fig, ax = plt.subplots(figsize=cfg["figure.size"])
    specs = [
        ("Established: Domain Specialist-led", "series.domain.color"),
        ("Chaperoned: AI Specialist-led", "series.chaperoned.color"),
        ("Independent: AI Specialist-led", "series.independent.color"),
    ]
    for category, color_path in specs:
        subset = data.loc[data["category"].eq(category)]
        ax.plot(subset["year"], subset["share_ewma5"], color=cfg[color_path],
                lw=cfg["series.lines.linewidth"], label=category)
    ax.set(xlabel=cfg["axes.main.xlabel"], ylabel=cfg["axes.main.ylabel"],
           xlim=(1995, 2024), ylim=(0, 1))
    ax.yaxis.set_major_formatter(PercentFormatter(1, decimals=0))
    ax.xaxis.set_major_locator(MultipleLocator(10))
    if cfg["legend.visible"]:
        ax.legend(frameon=False, fontsize=cfg["legend.font_size"],
                  handlelength=1.8, labelspacing=0.3, borderaxespad=0.2)
    ax.spines[["top", "right"]].set_visible(False)
    ax.tick_params(labelsize=cfg["typography.tick_size"], direction="out")
    ax.xaxis.label.set_size(cfg["typography.label_size"])
    ax.yaxis.label.set_size(cfg["typography.label_size"])
    ax.grid(False)
    fig.tight_layout()
    return fig

