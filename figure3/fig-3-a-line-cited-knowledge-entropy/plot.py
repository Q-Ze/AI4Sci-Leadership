def _resolved(settings):
    values = {field["path"]: field["default"] for field in PLOT_SCHEMA}
    values.update(settings or {})
    return values


def prepare_data():
    return pd.DataFrame(_DATA)


def render(data, settings):
    cfg = _resolved(settings)
    fig, ax = plt.subplots(figsize=cfg["figure.size"])
    for typ, label, color_path in [
        ("AI", "AI papers", "series.ai.color"),
        ("Domain", "Domain papers", "series.domain.color"),
    ]:
        subset = data.loc[data["cited_type"].eq(typ)]
        ax.plot(subset["year"], subset["entropy_global_ewma5"],
                color=cfg[color_path], lw=cfg["series.lines.linewidth"], label=label)
    ax.set(xlabel=cfg["axes.main.xlabel"], ylabel=cfg["axes.main.ylabel"],
           xlim=(1995, 2024), ylim=cfg["axes.main.y_range"])
    ax.yaxis.set_major_locator(MultipleLocator(0.1))
    ax.yaxis.set_major_formatter(FormatStrFormatter("%.1f"))
    ax.xaxis.set_major_locator(MultipleLocator(10))
    if cfg["inset.visible"]:
        wide = data.pivot(index="year", columns="cited_type", values="entropy_global")
        gap = (wide["Domain"] - wide["AI"]).ewm(span=5, adjust=False).mean()
        inset = ax.inset_axes([0.53, 0.095, 0.42, 0.27])
        inset.axhline(0, color="#777777", lw=0.6)
        inset.plot(gap.index, gap.values, color=cfg["series.gap.color"], lw=1.15)
        inset.set(xlim=(1995, 2024), ylim=(-0.05, 0.06), ylabel="Domain − AI")
        inset.set_yticks([-0.05, 0, 0.05])
        inset.xaxis.set_major_locator(MultipleLocator(10))
        inset.tick_params(labelsize=6, width=0.55, length=2.2, direction="out")
        inset.yaxis.label.set_size(6.5)
        inset.spines[["top", "right"]].set_visible(False)
        inset.grid(False)
    if cfg["legend.visible"]:
        ax.legend(frameon=False, fontsize=7.2, handlelength=1.8, labelspacing=0.3, borderaxespad=0.2)
    ax.xaxis.label.set_size(cfg["typography.label_size"])
    ax.yaxis.label.set_size(cfg["typography.label_size"])
    ax.tick_params(labelsize=cfg["typography.tick_size"], direction="out")
    ax.spines[["top", "right"]].set_visible(False)
    ax.grid(False)
    fig.tight_layout()
    return fig

