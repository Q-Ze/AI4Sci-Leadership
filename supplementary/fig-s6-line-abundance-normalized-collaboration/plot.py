def _resolved(settings):
    values = {field["path"]: field["default"] for field in PLOT_SCHEMA}
    values.update(settings or {})
    return values


def prepare_data():
    return pd.DataFrame(_DATA)


def render(data, settings):
    cfg = _resolved(settings)
    fig, ax = plt.subplots(figsize=cfg["figure.size"])
    ax.axhline(1, color=cfg["reference.parity.color"], lw=0.75, ls="--", zorder=1)
    for leader, label, color_path in [
        ("AI", "Domain in AI-led teams", "series.domain_in_ai.color"),
        ("Domain", "AI in Domain-led teams", "series.ai_in_domain.color"),
    ]:
        subset = data.loc[data["leader_class"].eq(leader)]
        ax.plot(subset["year"], subset["observed_expected_ratio_ewma5"], color=cfg[color_path],
                lw=cfg["series.lines.linewidth"], label=label, zorder=3)
    ax.set(xlim=(1995, 2024.2), ylim=cfg["axes.main.y_range"],
           xlabel=cfg["axes.main.xlabel"], ylabel=cfg["axes.main.ylabel"])
    ax.yaxis.set_major_locator(MultipleLocator(0.1))
    if cfg["legend.visible"]:
        ax.legend(frameon=False, fontsize=6.7, loc="upper left", bbox_to_anchor=(0.02, 0.94))
    ax.spines[["top", "right"]].set_visible(False)
    ax.tick_params(direction="out")
    ax.grid(False)
    fig.tight_layout()
    return fig

