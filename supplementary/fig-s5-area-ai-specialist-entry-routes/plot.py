def _resolved(settings):
    values = {field["path"]: field["default"] for field in PLOT_SCHEMA}
    values.update(settings or {})
    return values


def prepare_data():
    return pd.DataFrame(_DATA)


def render(data, settings):
    cfg = _resolved(settings)
    panels = [
        ("two_route", ["Entered as leader", "Entered via Domain-led team"], "A  Two focal routes"),
        ("three_route", ["Entered as leader", "Entered via AI-led team", "Entered via Domain-led team"], "B  Three-way routes"),
    ]
    color_map = {
        "Entered as leader": cfg["series.route.colors"][0],
        "Entered via AI-led team": cfg["series.route.colors"][1],
        "Entered via Domain-led team": cfg["series.route.colors"][2],
    }
    fig, axes = plt.subplots(1, 2, figsize=cfg["figure.size"], sharey=True)
    for axis, (panel, routes, title) in zip(axes, panels):
        subset = data.loc[data["panel"].eq(panel)]
        wide = subset.pivot(index="first_ai_lead_year", columns="route", values="share_ewma5").fillna(0)
        axis.stackplot(wide.index, *[wide[route] for route in routes], labels=routes,
                       colors=[color_map[route] for route in routes],
                       alpha=cfg["series.areas.alpha"], linewidth=0)
        axis.set(xlim=(1995, 2024), ylim=(0, 1), xlabel=cfg["axes.main.xlabel"], title=title)
        axis.title.set_fontsize(cfg["typography.title_size"])
        axis.spines[["top", "right"]].set_visible(False)
        axis.tick_params(direction="out")
        axis.grid(False)
        if cfg["legend.visible"]:
            axis.legend(frameon=True, facecolor="white", edgecolor="none", framealpha=0.9,
                        fontsize=cfg["legend.font_size"], loc="lower left", labelspacing=0.25)
    axes[0].set_ylabel(cfg["axes.main.ylabel"])
    axes[0].yaxis.set_major_formatter(PercentFormatter(1, decimals=0))
    fig.subplots_adjust(wspace=cfg["layout.wspace"], bottom=0.2)
    return fig

