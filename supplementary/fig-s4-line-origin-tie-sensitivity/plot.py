def _resolved(settings):
    values = {field["path"]: field["default"] for field in PLOT_SCHEMA}
    values.update(settings or {})
    return values


def prepare_data():
    return pd.DataFrame(_DATA)


def render(data, settings):
    cfg = _resolved(settings)
    y_min = max(0, float(data["ai_share"].min()) - 0.025)
    y_max = min(1, float(data["ai_share"].max()) + 0.025)
    styles = {"Ties to AI": "-", "Ties to Domain": "--", "Ties excluded": ":"}
    fig, axes = plt.subplots(1, 2, figsize=cfg["figure.size"], sharey=True)
    for axis, position in zip(axes, ["All authors", "Last authors"]):
        for specification, linestyle in styles.items():
            subset = data.loc[data["position"].eq(position) & data["specification"].eq(specification)]
            axis.plot(subset["year"], subset["ai_share"], color=cfg["series.ai.color"],
                      ls=linestyle, lw=cfg["series.lines.linewidth"], label=specification)
        axis.set(xlim=(1995, 2024), ylim=(y_min, y_max),
                 xlabel=cfg["axes.main.xlabel"], title=position)
        axis.title.set_fontsize(cfg["typography.title_size"])
        axis.spines[["top", "right"]].set_visible(False)
        axis.tick_params(labelsize=cfg["typography.tick_size"], direction="out")
        axis.grid(False)
    axes[0].set_ylabel(cfg["axes.main.ylabel"])
    axes[0].yaxis.set_major_formatter(PercentFormatter(1, decimals=0))
    if cfg["legend.visible"]:
        axes[0].legend(frameon=False)
    fig.subplots_adjust(wspace=cfg["layout.wspace"], bottom=0.2)
    return fig

