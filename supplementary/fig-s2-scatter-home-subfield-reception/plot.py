def _resolved(settings):
    values = {field["path"]: field["default"] for field in PLOT_SCHEMA}
    values.update(settings or {})
    return values


def _limits(values):
    values = values.dropna()
    return min(0.0, float(values.min()) - 0.06), max(1.25, float(values.max()) + 0.06)


def _kde(axis, values, limits, color, orientation, width):
    values = values.dropna().to_numpy()
    support = np.linspace(*limits, 256)
    density = gaussian_kde(values)(support)
    if orientation == "horizontal":
        axis.plot(support, density, color=color, lw=width)
        axis.fill_between(support, 0, density, color=color, alpha=0.10)
    else:
        axis.plot(density, support, color=color, lw=width)
        axis.fill_betweenx(support, 0, density, color=color, alpha=0.10)


