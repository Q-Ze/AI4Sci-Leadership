def render(data, settings):
    cfg = _resolved(settings)
    specs = [
        ("outside_normalized", "Citing audience (y-axis):\nAll outside subfields"),
        ("other_science_normalized", "Citing audience (y-axis):\nOutside subfields w/o CS"),
        ("computer_science_normalized", "Citing audience (y-axis):\nComputer Science subfields"),
    ]
    xlim = _limits(data["home_normalized"])
    ylim = _limits(pd.concat([data[key] for key, _ in specs], ignore_index=True))
    fig = plt.figure(figsize=cfg["figure.size"])
    outer = fig.add_gridspec(2, 3, left=0.075, right=0.975, bottom=0.13, top=0.93,
                             wspace=cfg["layout.wspace"], hspace=cfg["layout.hspace"])
    for row, leader in enumerate(["AI", "Domain"]):
        group = data.loc[data["leader_class"].eq(leader)]
        color = cfg["series.ai.color"] if leader == "AI" else cfg["series.domain.color"]
        for col, (column, title) in enumerate(specs):
            inner = outer[row, col].subgridspec(4, 4, width_ratios=[1, 1, 1, 0.42],
                                                height_ratios=[0.42, 1, 1, 1], hspace=0.04, wspace=0.04)
            ax_top = fig.add_subplot(inner[0, :3])
            ax = fig.add_subplot(inner[1:, :3])
            ax_right = fig.add_subplot(inner[1:, 3], sharey=ax)
            ax.scatter(group["home_normalized"], group[column], s=cfg["series.points.size"],
                       color=color, edgecolor="white", linewidth=0.25,
                       alpha=cfg["series.points.alpha"], zorder=3)
            ax.set(xlim=xlim, ylim=ylim)
            ax.axvline(1, color=cfg["reference.parity.color"], lw=0.7, ls="--")
            ax.axhline(1, color=cfg["reference.parity.color"], lw=0.7, ls="--")
            ax.xaxis.set_major_locator(MaxNLocator(nbins=4))
            ax.yaxis.set_major_locator(MaxNLocator(nbins=4))
            ax.spines[["top", "right"]].set_visible(False)
            ax.tick_params(direction="out", labelsize=cfg["typography.tick_size"])
            if col == 1:
                ax.set_xlabel("Within-home-subfield normalized citations", fontsize=8.3)
            if col == 0:
                ax.set_ylabel("Outside-home-subfield\nnormalized citations", fontsize=8.3)
            if row == 0:
                ax_top.set_title(title, fontsize=cfg["typography.title_size"], pad=3)
            _kde(ax_top, group["home_normalized"], xlim, color, "horizontal", cfg["series.density.linewidth"])
            _kde(ax_right, group[column], ylim, color, "vertical", cfg["series.density.linewidth"])
            ax_top.set_xlim(*xlim)
            ax_right.set_ylim(*ylim)
            ax_top.set_xticks([])
            ax_top.set_yticks([])
            ax_right.set_xticks([])
            ax_right.tick_params(axis="y", left=False, right=False, labelleft=False, labelright=False)
            for marginal in (ax_top, ax_right):
                marginal.spines[:].set_visible(False)
            if col == 0:
                label = "AI Specialist-led" if leader == "AI" else "Domain Specialist-led"
                ax.text(0.04, 0.06, label, transform=ax.transAxes, ha="left", va="bottom",
                        color=color, fontsize=7, fontweight="bold")
    return fig

