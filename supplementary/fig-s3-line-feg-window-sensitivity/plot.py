def _resolved(settings):
    values = {field["path"]: field["default"] for field in PLOT_SCHEMA}
    values.update(settings or {})
    return values


def _padded(values, pad=0.005):
    low, high = float(values.min()), float(values.max())
    margin = max((high - low) * 0.08, pad)
    return max(0, low - margin), min(1, high + margin)


def prepare_data():
    return pd.DataFrame(_DATA)


def render(data, settings):
    cfg = _resolved(settings)
    fig, left_axes = plt.subplots(1, 3, figsize=cfg["figure.size"])
    for index, (axis, window) in enumerate(zip(left_axes, [3, 5, 10])):
        subset = data.loc[data["window"].eq(window)].sort_values("year")
        right = axis.twinx()
        axis.plot(subset["year"], subset["F_ewma5"], color=cfg["series.foundation.color"],
                  lw=cfg["series.lines.linewidth"], label="Foundation")
        right.plot(subset["year"], subset["E_ewma5"], color=cfg["series.extension.color"],
                   lw=cfg["series.lines.linewidth"], label="Extension")
        right.plot(subset["year"], subset["G_ewma5"], color=cfg["series.generalization.color"],
                   lw=cfg["series.lines.linewidth"], label="Generalization")
        axis.set(xlabel="AI4Sci publication year", xlim=(1995, int(subset["year"].max())),
                 ylim=_padded(subset["F_ewma5"]))
        right.set_ylim(_padded(subset[["E_ewma5", "G_ewma5"]].stack()))
        axis.set_title(f"{window}-year forward-citation window", fontsize=cfg["typography.title_size"], pad=5)
        axis.xaxis.set_major_locator(MultipleLocator(10))
        if index == 0:
            axis.set_ylabel("Foundation index")
        if index == 2:
            right.set_ylabel("Extension / Generalization index")
        for item in (axis, right):
            item.tick_params(labelsize=cfg["typography.tick_size"], direction="out")
            item.spines["top"].set_visible(False)
            item.grid(False)
        axis.spines["right"].set_visible(False)
        right.spines["left"].set_visible(False)
        right.spines["bottom"].set_visible(False)
        if index == 0 and cfg["legend.visible"]:
            handles = axis.lines + right.lines
            axis.legend(handles, [line.get_label() for line in handles], frameon=False, fontsize=6.7)
    fig.subplots_adjust(wspace=cfg["layout.wspace"], bottom=0.2, top=0.86)
    return fig

