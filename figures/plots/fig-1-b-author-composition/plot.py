def _resolved(settings):
    values = {field["path"]: field["default"] for field in PLOT_SCHEMA}
    values.update(settings or {})
    return values


def _parse_csv(text, integer_columns):
    return pd.DataFrame([
        {key: int(value) if key in integer_columns else float(value)
         for key, value in row.items()}
        for row in DictReader(StringIO(text))
    ])


def prepare_data():
    """Retain both original calculation tables, joined one-to-one by year."""
    authors = _parse_csv(_ALL_CSV_DATA, {"year", "AI", "Domain", "total_classified"})
    positions = _parse_csv(_POSITION_CSV_DATA, {
        "year", "first_ai_n", "first_domain_n", "last_ai_n", "last_domain_n",
    })
    return authors.merge(positions, on="year", validate="one_to_one", how="outer").sort_values("year").reset_index(drop=True)


def _text_style(config, key):
    prefix = f"annotations.{key}"
    return dict(
        fontfamily=config[f"{prefix}.font_family"],
        fontsize=config[f"{prefix}.font_size"],
        fontweight=config[f"{prefix}.font_weight"],
        color=config[f"{prefix}.color"],
        rotation=config[f"{prefix}.rotation"],
        ha=config[f"{prefix}.horizontal_alignment"], va="center",
    )


def _apply_axis_alignment(fig, ax, config):
    """Keep the original auto layout, or place axes at physical canvas margins."""
    ax.xaxis.labelpad = config["axes.main.x_label_pad"]
    ax.yaxis.labelpad = config["axes.main.y_label_pad"]
    ax.tick_params(axis="x", which="major", pad=config["axes.main.x_tick_pad"])
    ax.tick_params(axis="y", which="major", pad=config["axes.main.y_tick_pad"])
    if config["layout.mode"] == "auto":
        fig.tight_layout(pad=config["layout.padding"])
        return
    width_mm, height_mm = fig.get_size_inches() * 25.4
    left = config["layout.left_mm"]
    right = config["layout.right_mm"]
    bottom = config["layout.bottom_mm"]
    top = config["layout.top_mm"]
    if min(left, right, bottom, top) < 0 or left + right >= width_mm or bottom + top >= height_mm:
        raise ValueError("固定边距无效：左右边距之和须小于画布宽度，上下边距之和须小于画布高度。请减小边距或增大画布。")
    fig.set_layout_engine(None)
    fig.subplots_adjust(left=left / width_mm, right=1 - right / width_mm,
                        bottom=bottom / height_mm, top=1 - top / height_mm)


def render(data, settings):
    """Return one Figure; preserve source shares and independent denominators."""
    config = _resolved(settings)
    fig, ax = plt.subplots(figsize=tuple(config["figure.size"]), facecolor=config["figure.facecolor"])
    ax.set_facecolor(config["figure.facecolor"])
    ax.stackplot(
        data["year"], data["AI_share_ewma5"], data["Domain_share_ewma5"],
        colors=[config["series.ai.color"], config["series.domain.color"]],
        alpha=config["series.area.alpha"], edgecolor="none", linewidth=0,
        zorder=1,
    )
    series = [
        ("all", "AI_share_ewma5"),
        ("first", "first_ai_share_ewma5"),
        ("last", "last_ai_share_ewma5"),
    ]
    for role, column in series:
        ax.plot(
            data["year"], data[column], color=config[f"series.{role}.color"],
            linewidth=config[f"series.{role}.linewidth"],
            linestyle=("-" if config[f"series.{role}.linestyle"] == "-"
                       else (0, tuple(config[f"series.{role}.dashes"]))),
            label=role.title(), zorder=3,
        )
        prefix = f"annotations.{role}"
        if config[f"{prefix}.visible"]:
            target_year = config[f"{prefix}.target_year"]
            target_share = float(np.interp(target_year, data["year"], data[column]))
            arrowprops = None
            if config[f"{prefix}.leader_visible"]:
                arrowprops = dict(
                    arrowstyle="-", color=config[f"{prefix}.leader_color"],
                    linewidth=config[f"{prefix}.leader_width"],
                    linestyle=config[f"{prefix}.leader_style"],
                    shrinkA=config[f"{prefix}.leader_gap"], shrinkB=0,
                )
            ax.annotate(
                config[f"{prefix}.text"], xy=(target_year, target_share),
                xycoords="data", xytext=config[f"{prefix}.position"],
                textcoords="axes fraction", arrowprops=arrowprops,
                **_text_style(config, role), zorder=5,
            )
    for key in ("ai", "domain"):
        prefix = f"annotations.{key}"
        if config[f"{prefix}.visible"]:
            ax.text(
                *config[f"{prefix}.position"], config[f"{prefix}.text"],
                transform=ax.transAxes, **_text_style(config, key), zorder=5,
            )
    ax.set_xlabel(config["axes.main.x_label"], family=config["typography.font_family"], fontsize=config["typography.label_size"])
    ax.set_ylabel(config["axes.main.y_label"], family=config["typography.font_family"], fontsize=config["typography.label_size"])
    ax.set_xlim(*config["axes.main.x_range"])
    ax.set_ylim(*config["axes.main.y_range"])
    ax.yaxis.set_major_formatter(PercentFormatter(1, decimals=0, symbol=config["axes.main.percent_symbol"]))
