def prepare_data():
    integer_columns = {"year", "all_n_papers", "ai_n_papers", "domain_n_papers"}
    rows = []
    for row in DictReader(StringIO(_CSV_DATA)):
        rows.append({
            key: int(float(value)) if key in integer_columns else float(value)
            for key, value in row.items()
        })
    return pd.DataFrame(rows)


def _resolved(settings):
    values = {field["path"]: field["default"] for field in PLOT_SCHEMA}
    values.update(settings or {})
    return values


def _limits(frame, padding, minimum):
    low, high = float(frame.min().min()), float(frame.max().max())
    pad = max((high - low) * padding, minimum)
    return max(0, low - pad), min(1, high + pad)


def render(data, settings):
    c = _resolved(settings)
    if c["axes.x_range"][0] >= c["axes.x_range"][1]:
        raise ValueError("X 轴范围下限须小于上限。")
    width, height = c["figure.size"]
    if c["layout.mode"] == "mm":
        left = c["layout.left_mm"] / (width * 25.4)
        right = 1 - c["layout.right_mm"] / (width * 25.4)
        bottom = c["layout.bottom_mm"] / (height * 25.4)
        top = 1 - c["layout.top_mm"] / (height * 25.4)
    else:
        left, right, bottom, top = (c[f"layout.{side}"] for side in ("left", "right", "bottom", "top"))
    if not (0 <= left < right <= 1 and 0 <= bottom < top <= 1):
        raise ValueError("边距无效：请减小边距或增大画布，确保绘图区有正的宽度和高度。")
    style = {"font.family": c["typography.font_family"],
             "axes.labelsize": c["typography.label_size"],
             "xtick.labelsize": c["typography.tick_size"],
             "ytick.labelsize": c["typography.tick_size"]}
    with plt.rc_context(style):
        fig, ax = plt.subplots(figsize=tuple(c["figure.size"]), facecolor=c["figure.facecolor"])
        metric, key = "F", "foundation"
        ax.set_facecolor(c["figure.facecolor"])
        columns = []
        for group in ("all", "ai", "domain"):
            column = f"{group}_{metric}_ewma5"
            columns.append(column)
            ax.plot(data.year, data[column], color=c[f"series.{group}.color"],
                    lw=c["series.linewidth"] * c[f"series.{group}.width_scale"],
                    ls=c[f"series.{group}.linestyle"], alpha=c[f"series.{group}.alpha"],
                    label=c[f"series.{group}.label"])
        ax.set_title(c[f"axes.{key}.title"], fontsize=c["typography.title_size"], pad=c["axes.title_pad"])
        ax.set_xlabel(c["axes.x_label"], labelpad=c["axes.x_label_pad"])
        ax.set_ylabel(c[f"axes.{key}.y_label"], labelpad=c["axes.y_label_pad"])
        ax.set_xlim(*c["axes.x_range"])
        limits = (_limits(data[columns], c["axes.y_padding_fraction"], c["axes.y_minimum_pad"])
                  if c[f"axes.{key}.y_auto"] else c[f"axes.{key}.y_range"])
        if limits[0] >= limits[1]:
            raise ValueError(f"{key} 的 Y 轴范围下限须小于上限。")
        ax.set_ylim(*limits)
        ax.xaxis.set_major_locator(MultipleLocator(c["axes.x_tick_step"]))
        if c[f"axes.{key}.y_tick_step"] > 0:
            ax.yaxis.set_major_locator(MultipleLocator(c[f"axes.{key}.y_tick_step"]))
        decimals = c[f"axes.{key}.y_decimals"]
        if c[f"axes.{key}.y_format"] == "percent":
            ax.yaxis.set_major_formatter(PercentFormatter(1, decimals=decimals))
        else:
            ax.yaxis.set_major_formatter(StrMethodFormatter("{x:." + str(decimals) + "f}"))
        ax.tick_params(direction="out", labelsize=c["typography.tick_size"],
                       width=c["axes.spine_width"], length=c["axes.tick_length"])
        ax.tick_params(axis="x", pad=c["axes.x_tick_pad"])
        ax.tick_params(axis="y", pad=c["axes.y_tick_pad"])
        for side in ("top", "right"):
            ax.spines[side].set_visible(False)
        for side in ("left", "bottom"):
            ax.spines[side].set_linewidth(c["axes.spine_width"])
        ax.set_axisbelow(True)
        ax.grid(False)
        if c["axes.grid_visible"]:
            ax.grid(axis="y", color=c["axes.grid_color"], alpha=c["axes.grid_alpha"], linewidth=c["axes.grid_width"])
        for group in ("all", "ai", "domain"):
            prefix = f"annotations.{key}.{group}"
            if not c[f"{prefix}.visible"]:
                continue
            year = c[f"{prefix}.year"]
            value = float(np.interp(year, data.year, data[f"{group}_{metric}_ewma5"]))
            color = c[f"series.{group}.color"] if c[f"{prefix}.follow_color"] else c[f"{prefix}.color"]
            arrow = None
            if c[f"{prefix}.leader"]:
                arrow = dict(arrowstyle="-", color=color, linewidth=c["annotations.leader_width"],
                             linestyle=c["annotations.leader_style"], shrinkA=2, shrinkB=2,
                             connectionstyle="arc3,rad=0", alpha=.7)
            background = dict(facecolor=c["figure.facecolor"], edgecolor="none", pad=1) if c["annotations.background"] else None
            ax.annotate(c[f"{prefix}.text"], xy=(year, value), xycoords="data",
                        xytext=tuple(c[f"{prefix}.offset"]), textcoords="offset points",
                        color=color, fontsize=c[f"{prefix}.font_size"],
                        fontfamily=c["typography.font_family"],
                        ha=c[f"{prefix}.align"], va="center", arrowprops=arrow,
                        bbox=background, zorder=5, annotation_clip=True)
        fig.subplots_adjust(left=left, right=right, bottom=bottom, top=top)
        return fig
